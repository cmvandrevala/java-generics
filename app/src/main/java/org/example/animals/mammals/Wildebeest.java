package org.example.animals.mammals;

public class Wildebeest extends Mammal{

  @Override
  public void feed() {
    System.out.println("Wildebeest are herbivores that feed on fresh, nutrient-rich grasses.");
  }

  @Override
  public void observe() {
    System.out.println("Wildebeests are known for their white beards, silvery-blue coats, long black tails and cow-like horns.");
  }
}
