package org.example.animals.insects;

public class Ladybug extends Insect {

  @Override
  public void feed() {
    System.out.println("Believe it or not, ladybugs are primarily carnivorous predators that feast on soft-bodied insects.");
  }

  @Override
  public void observe() {
    System.out.println("Ladybugs undergo complete metamorphosis through four distinct stages: egg, larva, pupa, and adult.");
  }
}
