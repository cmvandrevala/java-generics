package org.example.animals.insects;

public class Bumblebee extends Insect {

  @Override
  public void feed() {
    System.out.println("Bumblebees dine on nectar and pollen from plants!");
  }

  @Override
  public void observe() {
    System.out.println("Bumblebees fly using rapid wing rotation and vortex generation - not just by simply flapping their wings up and down!");
  }
}
